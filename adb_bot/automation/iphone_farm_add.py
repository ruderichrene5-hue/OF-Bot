"""Add a physical iPhone to the farm dashboard in one command, and keep the
relay box (the machine the iPhones are cabled to) in sync with the config.

    .venv/bin/python -m adb_bot.automation.iphone_farm_add \\
        --name "iPhone 3 (weiß)" --ip 192.168.1.130 --vnc-password iphone3
    .venv/bin/python -m adb_bot.automation.iphone_farm_add --sync   # just re-sync the relay

What the phone needs first (by hand, once): palera1n jailbreak, CatVNC (with a
password), Crane, OpenSSH, Shadowrocket, our SSH key (/iphone-ssh-setup), Wi-Fi,
a row in the Reels base's Device table (its "iPhone UID" is --name).

What this does:
1. checks SSH (mobile + ~/.ssh/iphone_farm) and the CatVNC password;
2. writes the phone into /etc/adbbot/iphone_farm.json with the next free
   number N: stream "iphoneN", AirPlay receiver "Farm iPhone NN";
3. regenerates the relay from that file -- one UxPlay LaunchAgent per phone,
   mediamtx.yml, the VNC token file -- and restarts what changed;
4. restarts the server's VNC bridge. The watchdog starts mirroring within a
   minute (it needs the receiver to exist, which step 3 just did).

Receiver names are zero-padded ("Farm iPhone 01") so the iOS picker, which
lists them alphabetically, puts them in number order: `picker_row` is derived
from that order for every phone on every sync, and a wrong row would make a
phone mirror into -- and, with -nohold, kick -- another phone's receiver.

Only a macOS relay is implemented (Rene's MacBook, 2026-10-03). The Linux mini
PC needs the same three files as systemd units + vaapi/x264 instead of vtenc.
"""

from __future__ import annotations

import argparse
import json
import plistlib
import shlex
import subprocess
import sys

from adb_bot.automation import iphone_farm_config, iphone_farm_vnc

SSH_KEY = iphone_farm_config.SSH_KEY
SSH_OPTS = ["-o", "BatchMode=yes", "-o", "StrictHostKeyChecking=no", "-o", "ConnectTimeout=30"]


def receiver_name(n: int) -> str:
    return f"Farm iPhone {n:02d}"


def _video_sink(udp_port: int) -> str:
    # Decoded mirror -> compositor over a live 60 fps black source, so a static screen still yields a
    # steady stream with a keyframe every second. UxPlay appends " sync=true" to the LAST element, so
    # a dummy fakesink branch takes it instead of udpsink (which must not wait on timestamps).
    return ("queue ! videoconvert ! c.sink_1 videotestsrc is-live=true pattern=black ! "
            "video/x-raw,width=16,height=16,framerate=60/1 ! videoconvert ! c.sink_0 "
            "compositor name=c background=black sink_1::zorder=1 ! videoconvert ! "
            "video/x-raw,format=NV12,framerate=60/1 ! queue max-size-buffers=2 leaky=2 ! "
            "vtenc_h264 realtime=true allow-frame-reordering=false max-keyframe-interval=60 bitrate=6000 ! "
            "h264parse ! rtph264pay config-interval=1 pt=96 ! "
            f"udpsink host=127.0.0.1 port={udp_port} sync=false async=false  "
            "videotestsrc is-live=true num-buffers=1 ! fakesink async=false")


def _uxplay_plist(n: int, home: str) -> bytes:
    label = f"com.veralta.uxplay{n}"
    return plistlib.dumps({
        "Label": label,
        "ProgramArguments": ["/usr/bin/script", "-q", "-F", f"{home}/farm/logs/{label}.tty",
                             f"{home}/UxPlay/build/uxplay", "-n", receiver_name(n), "-nh",
                             "-p", str(39000 + 100 * n), "-m", f"02:00:00:f1:00:{n:02x}",
                             "-fps", "60", "-nohold", "-reset", "0", "-vs", _video_sink(5000 + n)],
        "EnvironmentVariables": {"PATH": "/opt/homebrew/bin:/usr/bin:/bin",
                                 "DYLD_FALLBACK_LIBRARY_PATH": "/opt/homebrew/lib"},
        "StandardOutPath": "/dev/null", "StandardErrorPath": "/dev/null",
        "RunAtLoad": True, "KeepAlive": True,
    })


def _mediamtx_yml(numbers: list[int], tailnet_ip: str) -> str:
    head = f"""# GENERATED by adb_bot.automation.iphone_farm_add -- edit there, not here.
# iPhone farm video relay: UxPlay (one per phone) sends RTP/H264 to udp 500N; browsers read WebRTC :8889/iphoneN.
logLevel: info
# UxPlay pads a static screen to a steady 60 fps, so silence really means the mirroring session ended
readTimeout: 10s
api: true
apiAddress: :9997
authInternalUsers:
  # only UxPlay on this box may feed streams; tailnet viewers may watch and ask for status
  - user: any
    ips: [127.0.0.1, "::1"]
    permissions: [{{action: publish}}, {{action: read}}, {{action: playback}}, {{action: api}}]
  - user: any
    ips: [100.64.0.0/10, "fd7a:115c:a1e0::/48"]
    permissions: [{{action: read}}, {{action: api}}]
rtmp: false
hls: false
srt: false
rtsp: true
webrtc: true
webrtcAddress: :8889
webrtcLocalUDPAddress: :8189
webrtcAdditionalHosts: [{tailnet_ip}]
webrtcAllowOrigins: ["*"]
paths:
"""
    body = ""
    for n in numbers:
        body += f"""  iphone{n}:
    source: udp+rtp://127.0.0.1:{5000 + n}
    rtpSDP: |
      v=0
      o=- 0 0 IN IP4 127.0.0.1
      s=iphone{n}
      c=IN IP4 127.0.0.1
      t=0 0
      m=video {5000 + n} RTP/AVP 96
      a=rtpmap:96 H264/90000
      a=fmtp:96 packetization-mode=1
"""
    return head + body


def _ssh(target: str, cmd: str, stdin: bytes | None = None, timeout: int = 60) -> str:
    r = subprocess.run(["ssh", "-i", SSH_KEY, *SSH_OPTS, target, cmd], input=stdin,
                       capture_output=True, timeout=timeout)
    if r.returncode != 0:
        raise RuntimeError(f"ssh {target}: {r.stderr.decode(errors='replace').strip()[-300:]}")
    return r.stdout.decode(errors="replace")


def _number(phone: dict) -> int:
    return int(str(phone["stream"]).removeprefix("iphone"))


def sync_relay(dry_run: bool = False) -> list[str]:
    """Make the relay box match /etc/adbbot/iphone_farm.json. Returns what changed."""
    raw = iphone_farm_config._raw()
    relay = raw.get("_relay") or {}
    target, platform = relay.get("ssh"), relay.get("platform", "macos")
    if not target:
        raise SystemExit("_relay.ssh missing in iphone_farm.json (e.g. \"reneof@100.89.142.87\")")
    if platform != "macos":
        raise SystemExit(f"relay platform {platform!r} not implemented yet (only macos)")
    if relay.get("video") == "usb":
        return sync_usb_relay(raw, target, dry_run)
    tailnet_ip = target.split("@")[-1]
    phones = {k: v for k, v in raw.items() if not k.startswith("_") and v.get("stream")}
    numbers = sorted(_number(p) for p in phones.values())

    # picker order = alphabetical receiver names = number order thanks to zero padding
    order = sorted(phones, key=lambda k: receiver_name(_number(phones[k])))
    for row, rec_id in enumerate(order):
        phones[rec_id]["picker_row"] = row
        phones[rec_id]["receiver"] = receiver_name(_number(phones[rec_id]))
    changes = []
    if not dry_run:
        with open(iphone_farm_config.CONFIG_PATH, "w", encoding="utf-8") as f:
            json.dump(raw, f, indent=2)

    home = _ssh(target, "echo $HOME").strip()
    files = {f"{home}/farm/mediamtx.yml": _mediamtx_yml(numbers, tailnet_ip).encode(),
             f"{home}/farm/vnc-tokens": "".join(f"{k}: {v['ip']}:5900\n" for k, v in phones.items()).encode()}
    for n in numbers:
        files[f"{home}/Library/LaunchAgents/com.veralta.uxplay{n}.plist"] = _uxplay_plist(n, home)

    for path, content in files.items():
        current = subprocess.run(["ssh", "-i", SSH_KEY, *SSH_OPTS, target, f"cat {shlex.quote(path)} 2>/dev/null"],
                                 capture_output=True, timeout=30).stdout
        if current == content:
            continue
        changes.append(path)
        if not dry_run:
            _ssh(target, f"mkdir -p $(dirname {shlex.quote(path)}) && cat > {shlex.quote(path)}", stdin=content)

    if dry_run:
        return changes
    restart = []
    for path in changes:
        if path.endswith(".plist"):
            restart.append(path.rsplit("/", 1)[1].removesuffix(".plist"))
        elif path.endswith("mediamtx.yml"):
            restart.append("com.veralta.mediamtx")
    script = "U=$(id -u); mkdir -p ~/farm/logs; "
    for label in restart:
        p = f"$HOME/Library/LaunchAgents/{label}.plist"
        script += (f"launchctl bootout gui/$U/{label} 2>/dev/null; "
                   f"for i in 1 2 3 4 5 6 7 8; do sleep 2; launchctl bootstrap gui/$U {p} 2>/dev/null && break; done; ")
    if restart:
        _ssh(target, script, timeout=200)
    # the websockify on the relay re-reads its token file per connection; nothing to restart there
    subprocess.run(["systemctl", "restart", "adbbot-vnc-bridge"], check=False)
    return changes


def _agent_plist(label: str, args: list[str], home: str) -> bytes:
    return plistlib.dumps({
        "Label": label, "ProgramArguments": args,
        "EnvironmentVariables": {"PATH": "/opt/homebrew/bin:/usr/bin:/bin"},
        "StandardOutPath": f"{home}/farm/logs/{label}.log", "StandardErrorPath": f"{home}/farm/logs/{label}.log",
        "RunAtLoad": True, "KeepAlive": True, "ThrottleInterval": 15,
    })


def sync_usb_relay(raw: dict, target: str, dry_run: bool = False) -> list[str]:
    """Relay with the phones on USB (Mac mini, 2026-10-06): one usbcap2 per phone grabs the
    screen over the cable (QuickTime's route, ~10 % of a core vs ~45 % for AirPlay/UxPlay)
    and feeds RTP to mediamtx on udp 500N -- no AirPlay, no Wi-Fi load, no Control Center taps.
    Phones need "udid" and "stream" in the config."""
    tailnet_ip = target.split("@")[-1]
    phones = {k: v for k, v in raw.items() if not k.startswith("_") and isinstance(v, dict)
              and v.get("stream") and v.get("udid")}
    numbers = sorted(_number(p) for p in phones.values())
    home = _ssh(target, "echo $HOME").strip()
    files = {f"{home}/farm/mediamtx.yml": _mediamtx_yml(numbers, tailnet_ip).encode(),
             f"{home}/Library/LaunchAgents/com.veralta.mediamtx.plist": _agent_plist(
                 "com.veralta.mediamtx", [f"{home}/farm/bin/mediamtx", f"{home}/farm/mediamtx.yml"], home)}
    # macOS 27 lists iPhone screens under its own UUIDs, not the UDID (Mac mini, 2026-10-06), and two
    # phones were both "Rene's iPhone" -- so every phone gets the unique name "Farm iPhone NN"
    # (idevicename, over USB) and usbcap2 matches the UDID or that name.
    rename = "; ".join(f"/opt/homebrew/bin/idevicename -u {p['udid']} {shlex.quote(receiver_name(_number(p)))} >/dev/null 2>&1"
                       for p in phones.values())
    if rename and not dry_run:
        _ssh(target, rename + "; true", timeout=60)
    # VNC (touches from the Live page) over the USB cable too: websockify runs as a LaunchAgent and
    # macOS's Local Network privacy blocks agents from 192.168.x.x ("Failed to connect to downstream
    # server", 2026-10-08), while 127.0.0.1 through iproxy is always allowed -- and phones D/E have
    # no LAN address at all. Port 5900+N on the Mac -> 5900 on phone N.
    files[f"{home}/farm/vnc-tokens"] = "".join(f"{k}: 127.0.0.1:{5900 + _number(v)}\n" for k, v in phones.items()).encode()
    for p in phones.values():
        n = _number(p)
        files[f"{home}/Library/LaunchAgents/com.veralta.vnc-fwd{n}.plist"] = _agent_plist(
            f"com.veralta.vnc-fwd{n}", ["/opt/homebrew/bin/iproxy", "-u", p["udid"], "-s", "127.0.0.1", f"{5900 + n}:5900"], home)
    for p in phones.values():
        n = _number(p)
        files[f"{home}/Library/LaunchAgents/com.veralta.usbcap{n}.plist"] = _agent_plist(
            # "screen_uuid": macOS's own id of this phone's screen device, pinned after macOS mixed up the
            # cached names of A and B (2026-10-08: window A showed B's screen) -- matching by it alone.
            f"com.veralta.usbcap{n}", [f"{home}/farm/usbcap2", *(["--udid", p["screen_uuid"]] if p.get("screen_uuid") else
                                                               ["--udid", p["udid"], "--udid", receiver_name(n)]),
                                       "--fps", "30", "--udp", str(5000 + n)], home)
    changes = []
    for path, content in files.items():
        current = subprocess.run(["ssh", "-i", SSH_KEY, *SSH_OPTS, target, f"cat {shlex.quote(path)} 2>/dev/null"],
                                 capture_output=True, timeout=30).stdout
        if current != content:
            changes.append(path)
            if not dry_run:
                _ssh(target, f"mkdir -p $(dirname {shlex.quote(path)}) && cat > {shlex.quote(path)}", stdin=content)
    if dry_run:
        return changes
    labels = {path.rsplit("/", 1)[1].removesuffix(".plist") for path in changes if path.endswith(".plist")}
    if any(c.endswith("mediamtx.yml") for c in changes):
        labels.add("com.veralta.mediamtx")
    script = "U=$(id -u); mkdir -p ~/farm/logs; "
    for label in sorted(labels):
        script += (f"launchctl bootout gui/$U/{label} 2>/dev/null; sleep 1; "
                   f"launchctl bootstrap gui/$U $HOME/Library/LaunchAgents/{label}.plist; ")
    for path in files:                                # unchanged but not loaded (fresh boot of the relay)
        if path.endswith(".plist"):
            label = path.rsplit("/", 1)[1].removesuffix(".plist")
            script += f"launchctl print gui/$U/{label} >/dev/null 2>&1 || launchctl bootstrap gui/$U {shlex.quote(path)}; "
    _ssh(target, script, timeout=120)
    return changes


def add_phone(name: str, ip: str, vnc_password: str) -> str:
    from adb_bot.automation import phone_dashboard
    devices = {str(r["fields"].get("iPhone UID", "")).strip().lower(): r["id"]
               for r in phone_dashboard._all(phone_dashboard.DEVICE_TABLE)}
    rec_id = devices.get(name.strip().lower())
    if not rec_id:
        raise SystemExit(f"No Device row with iPhone UID {name!r} in the Reels base -- add it in Airtable first.")

    r = subprocess.run(["ssh", "-n", "-i", SSH_KEY, *SSH_OPTS, f"mobile@{ip}", "which uiopen sbreload"],
                       capture_output=True, text=True, timeout=20)
    if r.returncode != 0:
        raise SystemExit(f"SSH to mobile@{ip} failed -- is OpenSSH installed and our key set up "
                         f"(/iphone-ssh-setup)? {r.stderr.strip()[-200:]}")
    try:
        with iphone_farm_vnc.Phone(ip, vnc_password) as p:
            size = f"{p.width}x{p.height}"
    except PermissionError:
        raise SystemExit("CatVNC rejected that password.")
    except OSError as exc:
        raise SystemExit(f"CatVNC not reachable on {ip}:5900 ({exc}) -- is it enabled?")

    raw = iphone_farm_config._raw()
    phones = {k: v for k, v in raw.items() if not k.startswith("_")}
    existing = phones.get(rec_id, {})
    used = {_number(v) for k, v in phones.items() if v.get("stream") and k != rec_id}
    n = _number(existing) if existing.get("stream") else next(i for i in range(1, 100) if i not in used)
    raw[rec_id] = {**existing, "ip": ip, "vnc_password": vnc_password, "stream": f"iphone{n}"}
    with open(iphone_farm_config.CONFIG_PATH, "w", encoding="utf-8") as f:
        json.dump(raw, f, indent=2)
    changes = sync_relay()
    return (f"{name} ({rec_id}) -> stream iphone{n}, receiver {receiver_name(n)!r}, VNC {size}.\n"
            f"Relay files changed: {len(changes)}. The watchdog starts its live video within ~1 minute; "
            f"reload the Phones page to see it.")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--name", help='Device "iPhone UID" in Airtable, e.g. "iPhone 3 (weiß)"')
    ap.add_argument("--ip", help="phone's LAN address")
    ap.add_argument("--vnc-password")
    ap.add_argument("--sync", action="store_true", help="only re-sync the relay from the config")
    ap.add_argument("--dry-run", action="store_true", help="with --sync: show what would change")
    a = ap.parse_args(argv)
    if a.sync:
        changes = sync_relay(dry_run=a.dry_run)
        print("would change:" if a.dry_run else "changed:", *changes or ["nothing"], sep="\n  ")
        return 0
    if not (a.name and a.ip and a.vnc_password):
        ap.error("--name, --ip and --vnc-password are required (or --sync)")
    print(add_phone(a.name, a.ip, a.vnc_password))
    return 0


if __name__ == "__main__":
    sys.exit(main())
